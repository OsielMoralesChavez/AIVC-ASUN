/**
 * Catálogo de herramientas de investigación de consulta gratuita.
 *
 * Fuente de datos ÚNICA y tipada, compartida por el frontend (tabla y filtros) y el backend (el
 * asistente valida contra ella que la IA no recomiende herramientas inexistentes). No se escribe
 * ninguna fila dentro del JSX.
 *
 * Distinción deliberada en `accessType` — "gratuita" no significa "todo el contenido es abierto":
 *  - `open-access`  : consulta Y contenido abiertos.
 *  - `free-search`  : la búsqueda es gratuita, pero algún documento enlazado puede estar restringido.
 *  - `free-account` : uso gratuito, requiere crear una cuenta sin costo.
 */

export type ResearchToolAccess = "open-access" | "free-search" | "free-account";

export type ResearchToolCategory =
  | "academic-articles"
  | "books"
  | "datasets"
  | "current-news"
  | "patents"
  | "research-workflow";

export type ResearchToolFullText = "open" | "partial" | "depends-on-source" | "not-applicable";

