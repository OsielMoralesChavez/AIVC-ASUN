export function getResearchTool(id: string): ResearchTool | undefined {
  return RESEARCH_TOOLS.find((t) => t.id === id);
}

/** Idiomas presentes en el catálogo, ordenados — alimenta el filtro sin duplicar la lista. */
export function researchToolLanguages(): string[] {
  return [...new Set(RESEARCH_TOOLS.flatMap((t) => t.languages))].sort();
}
